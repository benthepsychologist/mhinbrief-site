/* jurisdiction-map.js — click/keyboard a province, populate the receipt
   panel from window.__REGULATORS (injected server-side by
   layouts/jurisdictions/list.html from data/regulators.yaml, itself
   generated by scripts/gen-regulators-data.py — see that file's header
   for why this is a temporary bridge, not the real publish pipeline).
   Same interaction shape as theprojection's map.js: click node, panel
   updates in place, no navigation. No-JS users get the always-rendered
   <details class="map-fallback"> list instead (hidden here once JS
   confirms it can render the richer panel). */
(function () {
  var DATA = window.__REGULATORS || {};
  var NAMES = {
    AB: "Alberta", BC: "British Columbia", MB: "Manitoba", NB: "New Brunswick",
    NL: "Newfoundland and Labrador", NS: "Nova Scotia", NT: "Northwest Territories",
    NU: "Nunavut", ON: "Ontario", PE: "Prince Edward Island", QC: "Quebec",
    SK: "Saskatchewan", YT: "Yukon"
  };

  document.documentElement.classList.add("js");

  var svg = document.querySelector("#canada-map-svg svg");
  var panel = document.getElementById("reg-panel");
  if (!svg || !panel) return;

  Object.keys(NAMES).forEach(function (code) {
    if (DATA["ca-" + code.toLowerCase()]) {
      var g = document.getElementById(code);
      if (g) g.classList.add("has-data");
    }
  });

  function tierClass(tier) { return "rt rt-" + (tier || 3); }

  function render(code) {
    var name = NAMES[code] || code;
    var items = DATA["ca-" + code.toLowerCase()] || [];
    var html = '<p class="rp-eyebrow">Regulatory bodies</p><h3>' + name + "</h3>";
    if (!items.length) {
      html += '<p class="rp-empty">Not yet researched for this registry — ' +
        "check back as jurisdiction coverage expands.</p>";
    } else {
      items.forEach(function (it) {
        html += '<div class="reg-item"><div class="rn">' +
          '<span class="' + tierClass(it.tier) + '">' + (it.tier_label || "") + "</span>" +
          (it.website ? '<a href="' + it.website + '">' + it.name + "</a>" : it.name) +
          "</div>";
        var tags = "";
        if (it.status === "proposed") tags += '<span class="tag tag-proposed">Proposed</span>';
        if (it.verified === false) tags += '<span class="tag tag-unverified">Unverified</span>';
        if (tags) html += '<div class="rp-tags">' + tags + "</div>";
        html += "</div>";
      });
    }
    panel.innerHTML = html;
  }

  function select(code, g) {
    var prev = svg.querySelector(".province.selected");
    if (prev) prev.classList.remove("selected");
    if (g) g.classList.add("selected");
    render(code);
  }

  svg.querySelectorAll(".province").forEach(function (g) {
    g.addEventListener("click", function () { select(g.getAttribute("data-code"), g); });
    g.addEventListener("keydown", function (e) {
      if (e.key === "Enter" || e.key === " ") {
        e.preventDefault();
        select(g.getAttribute("data-code"), g);
      }
    });
  });

  panel.innerHTML = '<p class="rp-eyebrow">Regulatory bodies</p>' +
    '<p class="rp-empty">Click or tab to a province to see its regulators, ' +
    "colleges, and associations — each sourced and dated.</p>";
})();
